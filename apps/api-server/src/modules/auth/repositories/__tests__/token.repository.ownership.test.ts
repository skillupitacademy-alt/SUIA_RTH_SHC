import { TokenRepository } from '../token.repository';

describe('W1.2-SESS-01: Owner-scoped single-session revocation', () => {
  beforeEach(() => {
    vi.clearAllMocks();
    capturedPredicates = [];
    lastPredicate = null;
    testAdapter.reset();

    // Configure updateWhereMock to apply predicates to test adapter
    updateWhereMock.mockImplementation(async (predicate) => {
      if (lastPredicate) {
        return testAdapter.applyUpdate(lastPredicate, { revoked: true });
      }
      return 0;
    });
  });

  describe('Stateful ownership behavior: real predicate on independent rows', () => {
    it('A revokes A\'s target session; another A session stays active', async () => {
      // Setup: User A has TWO sessions
      testAdapter.insert({
        id: 'session-A1',
        userId: 'user-A',
        token: 'token-A1',
        revoked: false,
        expiresAt: new Date(Date.now() + 100000),
      });
      testAdapter.insert({
        id: 'session-A2',
        userId: 'user-A',
        token: 'token-A2',
        revoked: false,
        expiresAt: new Date(Date.now() + 100000),
      });

      const repo = new TokenRepository();

      // A revokes session-A1
      await repo.revokeById('session-A1', 'user-A');

      // Verify: session-A1 is revoked, session-A2 remains active
      const sessionA1 = testAdapter.findById('session-A1');
      const sessionA2 = testAdapter.findById('session-A2');

      expect(sessionA1?.revoked).toBe(true);
      expect(sessionA2?.revoked).toBe(false);
    });

    it('A cannot revoke B\'s session; B stays active', async () => {
      // Setup: User A and User B each have a session
      testAdapter.insert({
        id: 'session-B-laptop',
        userId: 'user-B',
        token: 'token-B',
        revoked: false,
        expiresAt: new Date(Date.now() + 100000),
      });
      testAdapter.insert({
        id: 'session-A-phone',
        userId: 'user-A',
        token: 'token-A',
        revoked: false,
        expiresAt: new Date(Date.now() + 100000),
      });

      const repo = new TokenRepository();

      // User A attempts to revoke B's session
      await repo.revokeById('session-B-laptop', 'user-A');

      // Verify: B's session remains active (predicate matched 0 rows)
      const sessionB = testAdapter.findById('session-B-laptop');
      const sessionA = testAdapter.findById('session-A-phone');

      expect(sessionB?.revoked).toBe(false);
      expect(sessionA?.revoked).toBe(false);
    });

    it('unknown session ID is safe no-op', async () => {
      // Setup: User A has one session
      testAdapter.insert({
        id: 'session-known',
        userId: 'user-A',
        token: 'token-known',
        revoked: false,
        expiresAt: new Date(Date.now() + 100000),
      });

      const repo = new TokenRepository();

      // Attempt to revoke unknown session
      await repo.revokeById('session-unknown', 'user-A');

      // Verify: known session remains unchanged
      const knownSession = testAdapter.findById('session-known');
      expect(knownSession?.revoked).toBe(false);
    });

    it('already-revoked session causes no further change', async () => {
      // Setup: Session already revoked
      testAdapter.insert({
        id: 'session-revoked',
        userId: 'user-A',
        token: 'token-revoked',
        revoked: true,
        expiresAt: new Date(Date.now() + 100000),
      });

      const repo = new TokenRepository();

      // Attempt to revoke again
      await repo.revokeById('session-revoked', 'user-A');

      // Verify: still revoked (idempotent)
      const session = testAdapter.findById('session-revoked');
      expect(session?.revoked).toBe(true);
    });

    it('enforces both sessionId and userId in WHERE clause', async () => {
      const repo = new TokenRepository();
      await repo.revokeById('session-abc', 'user-123');

      // Verify update was called
      expect(updateMock).toHaveBeenCalledTimes(1);
      expect(updateSetMock).toHaveBeenCalledWith({ revoked: true });
      expect(updateWhereMock).toHaveBeenCalledTimes(1);

      // Verify BOTH predicates are present
      const whereArg = updateWhereMock.mock.calls[0][0];
      expect(whereArg).toHaveProperty('op', 'and');
      expect(whereArg.conditions).toHaveLength(2);

      // Verify predicates captured both session ID and user ID
      const sessionPred = capturedPredicates.find(p => p.field === 'refreshTokens.id');
      const userPred = capturedPredicates.find(p => p.field === 'refreshTokens.userId');

      expect(sessionPred).toBeDefined();
      expect(sessionPred?.value).toBe('session-abc');
      expect(userPred).toBeDefined();
      expect(userPred?.value).toBe('user-123');
    });
  });

  describe('Runtime validation: fail-closed for missing owner', () => {
    it('throws when userId is undefined - zero persistence', async () => {
      testAdapter.insert({
        id: 'session-123',
        userId: 'user-valid',
        token: 'token-valid',
        revoked: false,
        expiresAt: new Date(Date.now() + 100000),
      });

      const repo = new TokenRepository();
      // @ts-expect-error Testing runtime validation bypass
      await expect(repo.revokeById('session-123', undefined))
        .rejects.toThrow('W1.2-SESS-01: userId is required');

      // Verify NO database write occurred
      expect(updateWhereMock).not.toHaveBeenCalled();

      // Verify session unchanged
      const session = testAdapter.findById('session-123');
      expect(session?.revoked).toBe(false);
    });

    it('throws when userId is empty string - zero persistence', async () => {
      testAdapter.insert({
        id: 'session-456',
        userId: 'user-valid',
        token: 'token-456',
        revoked: false,
        expiresAt: new Date(Date.now() + 100000),
      });

      const repo = new TokenRepository();
      await expect(repo.revokeById('session-456', ''))
        .rejects.toThrow('W1.2-SESS-01: userId is required');

      expect(updateWhereMock).not.toHaveBeenCalled();

      const session = testAdapter.findById('session-456');
      expect(session?.revoked).toBe(false);
    });

    it('throws when userId is whitespace-only - zero persistence', async () => {
      testAdapter.insert({
        id: 'session-789',
        userId: 'user-valid',
        token: 'token-789',
        revoked: false,
        expiresAt: new Date(Date.now() + 100000),
      });

      const repo = new TokenRepository();
      await expect(repo.revokeById('session-789', '   '))
        .rejects.toThrow('W1.2-SESS-01: userId is required');

      expect(updateWhereMock).not.toHaveBeenCalled();

      const session = testAdapter.findById('session-789');
      expect(session?.revoked).toBe(false);
    });

    it('throws when userId is not a string - zero persistence', async () => {
      testAdapter.insert({
        id: 'session-999',
        userId: 'user-valid',
        token: 'token-999',
        revoked: false,
        expiresAt: new Date(Date.now() + 100000),
      });

      const repo = new TokenRepository();
      // @ts-expect-error Testing runtime validation
      await expect(repo.revokeById('session-999', null))
        .rejects.toThrow('W1.2-SESS-01: userId is required');

      // @ts-expect-error Testing runtime validation
      await expect(repo.revokeById('session-999', 42))
        .rejects.toThrow('W1.2-SESS-01: userId is required');

      expect(updateWhereMock).not.toHaveBeenCalled();

      const session = testAdapter.findById('session-999');
      expect(session?.revoked).toBe(false);
    });
  });

  describe('Tenant isolation: colliding IDs remain scoped', () => {
    it('RTH user-A and SUIA user-A with colliding session IDs are independently scoped', async () => {
      // Create separate fixture stores for RTH and SUIA
      const rthAdapter = new StatefulTestAdapter();
      const suiaAdapter = new StatefulTestAdapter();

      // RTH tenant: user-A has session-100
      rthAdapter.insert({
        id: 'session-100',
        userId: 'user-A',
        token: 'token-rth-A',
        revoked: false,
        expiresAt: new Date(Date.now() + 100000),
      });

      // SUIA tenant: SAME user-A has SAME session-100 (collision)
      suiaAdapter.insert({
        id: 'session-100',
        userId: 'user-A',
        token: 'token-suia-A',
        revoked: false,
        expiresAt: new Date(Date.now() + 100000),
      });

      // Configure mock to use RTH adapter
      updateWhereMock.mockImplementationOnce(async (predicate) => {
        if (lastPredicate) {
          return rthAdapter.applyUpdate(lastPredicate, { revoked: true });
        }
        return 0;
      });

      // RTH repository instance revokes session-100 for user-A
      const rthRepo = new TokenRepository();
      await rthRepo.revokeById('session-100', 'user-A');

      // Verify: RTH session-100 is revoked
      const rthSession = rthAdapter.findById('session-100');
      expect(rthSession?.revoked).toBe(true);
      expect(rthSession?.token).toBe('token-rth-A');

      // Configure mock to use SUIA adapter
      vi.clearAllMocks();
      capturedPredicates = [];
      lastPredicate = null;
      updateWhereMock.mockImplementationOnce(async (predicate) => {
        if (lastPredicate) {
          return suiaAdapter.applyUpdate(lastPredicate, { revoked: true });
        }
        return 0;
      });

      // SUIA repository instance (different db binding)
      const suiaRepo = new TokenRepository();

      // Query SUIA's session-100 - should still be active
      const suiaSessionBefore = suiaAdapter.findById('session-100');
      expect(suiaSessionBefore?.revoked).toBe(false);
      expect(suiaSessionBefore?.token).toBe('token-suia-A');

      // Now SUIA user-A revokes their own session-100
      await suiaRepo.revokeById('session-100', 'user-A');

      // Verify: SUIA session-100 is now revoked
      const suiaSessionAfter = suiaAdapter.findById('session-100');
      expect(suiaSessionAfter?.revoked).toBe(true);
      expect(suiaSessionAfter?.token).toBe('token-suia-A');

      // Verify: RTH session-100 remains revoked (unchanged by SUIA operation)
      const rthSessionFinal = rthAdapter.findById('session-100');
      expect(rthSessionFinal?.revoked).toBe(true);
      expect(rthSessionFinal?.token).toBe('token-rth-A');
    });
  });

  describe('SECURITY REGRESSION: Controlled mutation proof', () => {
    it('PRE-FIX MUTATION: Repository without ownership check allows cross-user revocation', async () => {
      /**
       * This test demonstrates the original vulnerability by creating a
       * disposable copy of TokenRepository where only the owner predicate
       * is removed, proving that without the fix, cross-user revocation
       * would be possible.
       */

      // Setup: User B has a session
      testAdapter.reset();
      testAdapter.insert({
        id: 'session-victim',
        userId: 'user-B',
        token: 'token-victim',
        revoked: false,
        expiresAt: new Date(Date.now() + 100000),
      });

      // Verify session starts active
      expect(testAdapter.findById('session-victim')?.revoked).toBe(false);

      // Create vulnerable repository copy: remove owner predicate but keep valid actor identity
      class VulnerableTokenRepository extends TokenRepository {
        async revokeById(id: string, _userId: string) {
          // VULNERABILITY: Accept userId but don't enforce it in WHERE clause
          if (typeof _userId !== 'string' || _userId.trim().length === 0) {
            throw new Error('W1.2-SESS-01: userId is required for session revocation');
          }
          // Only match by session ID (no ownership check)
          await this.dbInstance.update(this.refreshTokensTable)
            .set({ revoked: true })
            .where({ op: 'eq', field: 'refreshTokens.id', value: id });
        }
      }

      // Configure mock to accept single-predicate
      vi.clearAllMocks();
      capturedPredicates = [];
      lastPredicate = null;
      updateWhereMock.mockImplementation(async (predicate) => {
        // Accept single eq predicate (no ownership)
        if (predicate && predicate.op === 'eq') {
          for (const session of testAdapter['sessions']) {
            if (session.id === predicate.value) {
              session.revoked = true;
              return 1;
            }
          }
        }
        return 0;
      });

      const vulnerableRepo = new VulnerableTokenRepository();

      // User A attempts to revoke B's session WITH valid identity supplied
      await vulnerableRepo.revokeById('session-victim', 'user-A');

      // VULNERABILITY DEMONSTRATED: User B's session was revoked
      const victimSession = testAdapter.findById('session-victim');
      expect(victimSession?.revoked).toBe(true);
      expect(victimSession?.userId).toBe('user-B');
    });

    it('POST-FIX: Production code with ownership check prevents cross-user revocation', async () => {
      /**
       * This proves the fix works against the same scenario
       */

      // Setup: User B has a session
      testAdapter.reset();
      testAdapter.insert({
        id: 'session-victim',
        userId: 'user-B',
        token: 'token-victim',
        revoked: false,
        expiresAt: new Date(Date.now() + 100000),
      });

      // Reset mock to use normal test adapter with ownership check
      vi.clearAllMocks();
      capturedPredicates = [];
      lastPredicate = null;
      updateWhereMock.mockImplementation(async (predicate) => {
        if (lastPredicate) {
          return testAdapter.applyUpdate(lastPredicate, { revoked: true });
        }
        return 0;
      });

      const repo = new TokenRepository();

      // User A attempts to revoke B's session WITH userId required
      await repo.revokeById('session-victim', 'user-A');

      // FIX VERIFIED: User B's session remains active (predicate matched 0 rows)
      const victimSession = testAdapter.findById('session-victim');
      expect(victimSession?.revoked).toBe(false);
      expect(victimSession?.userId).toBe('user-B');

      // Verify both predicates were enforced
      const sessionPred = capturedPredicates.find(p => p.field === 'refreshTokens.id');
      const userPred = capturedPredicates.find(p => p.field === 'refreshTokens.userId');
      expect(sessionPred?.value).toBe('session-victim');
      expect(userPred?.value).toBe('user-A'); // User A's ID, not B's
    });

    it('POST-FIX: Runtime validation prevents bypassing ownership check', async () => {
      testAdapter.reset();
      testAdapter.insert({
        id: 'session-protected',
        userId: 'user-B',
        token: 'token-protected',
        revoked: false,
        expiresAt: new Date(Date.now() + 100000),
      });

      const repo = new TokenRepository();

      // Attempt to bypass with missing userId
      // @ts-expect-error Testing runtime protection
      await expect(repo.revokeById('session-protected'))
        .rejects.toThrow('W1.2-SESS-01: userId is required');

      // Verify NO database operation occurred
      expect(updateWhereMock).not.toHaveBeenCalled();

      // Verify session unchanged
      const session = testAdapter.findById('session-protected');
      expect(session?.revoked).toBe(false);
    });
  });
});
