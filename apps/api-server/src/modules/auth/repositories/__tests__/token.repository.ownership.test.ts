import { beforeEach, describe, expect, it, vi } from 'vitest';

/**
 * W1.2-SESS-01: Owner-scoped single-session revocation security tests
 *
 * OBJECTIVE: Prove that revokeById enforces ownership at the repository boundary.
 *
 * These tests verify:
 * 1. Owner A can revoke A's session; other A sessions remain unchanged
 * 2. A cannot revoke B's session in the same platform; B remains active
 * 3. Missing/empty/whitespace owner fails before persistence
 * 4. RTH and SUIA fixtures with colliding user/session IDs remain separately scoped
 * 5. Unknown/already-revoked session and repeated call retain safe behavior
 *
 * SECURITY REGRESSION: Includes controlled pre-fix mutation test proving
 * the original defect would have allowed cross-user revocation.
 */

/**
 * STATEFUL TEST ADAPTER: Simulates actual database behavior
 * Applies real generated predicates to independent fixture rows
 */
interface SessionRow {
  id: string;
  userId: string;
  token: string;
  revoked: boolean;
  expiresAt: Date;
}

class StatefulTestAdapter {
  private sessions: SessionRow[] = [];

  reset() {
    this.sessions = [];
  }

  insert(row: SessionRow) {
    this.sessions.push({ ...row });
  }

  findAll() {
    return this.sessions.map(s => ({ ...s }));
  }

  findById(id: string) {
    return this.sessions.find(s => s.id === id);
  }

  /**
   * Applies the real predicate generated by revokeById
   * Returns the number of rows affected (like a real database)
   */
  applyUpdate(predicate: any, updates: Partial<SessionRow>): number {
    if (!predicate || predicate.op !== 'and') {
      throw new Error('Expected AND predicate');
    }

    const conditions = predicate.conditions;
    let affectedCount = 0;

    for (const session of this.sessions) {
      let matches = true;

      for (const cond of conditions) {
        if (cond.op === 'eq') {
          const field = cond.field.split('.').pop();
          if (session[field as keyof SessionRow] !== cond.value) {
            matches = false;
            break;
          }
        }
      }

      if (matches) {
        Object.assign(session, updates);
        affectedCount++;
      }
    }

    return affectedCount;
  }
}

