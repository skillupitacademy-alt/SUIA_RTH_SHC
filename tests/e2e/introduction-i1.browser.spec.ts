/**
 * Classification-based browser evidence.
 * 
 * Actual uncaught JavaScript exceptions remain strict failures.
 * Unexpected console.error() messages remain strict failures.
 * Known development diagnostics are recorded for visibility.
 * Accessibility tool output is recorded separately.
 * Network failures remain strict unless explicitly classified.
 * Known authentication probes are recorded separately.
 */
interface BrowserEvidence {
  pageErrors: string[];
  unexpectedConsoleErrors: string[];
  expectedDiagnostics: string[];
  accessibilityFindings: string[];
  failedRequests: string[];
  expectedAuthProbes: string[];
}

interface ExpectedAuthProbe {
  method: string;
  urlPattern: string;
  status: number;
  description: string;
}

const EXPECTED_AUTH_PROBES: ExpectedAuthProbe[] = [
  {
    method: 'GET',
    urlPattern: '/api/tutorial/progress',
    status: 401,
    description: 'progress API probe',
  },
];

function isExpectedAuthProbe(
  method: string,
  url: string,
  status: number,
): ExpectedAuthProbe | undefined {
  return EXPECTED_AUTH_PROBES.find((probe) => {
    return (
      probe.method === method &&
      status === probe.status &&
      url.includes(probe.urlPattern)
    );
  });
}

function captureBrowserEvidence(page: Page): BrowserEvidence {
  const evidence: BrowserEvidence = {
    pageErrors: [],
    unexpectedConsoleErrors: [],
    expectedDiagnostics: [],
    accessibilityFindings: [],
    failedRequests: [],
    expectedAuthProbes: [],
  };

  /**
   * These patterns represent messages that have been investigated
   * and are known to be generated by the current test environment
   * or development instrumentation.
   * 
   * Keep this list narrow.
   */
  const KNOWN_DEV_DIAGNOSTICS = [
    '[AUTH_VALIDATE] Gateway URL unavailable for SSR auth validation',
  ];

  /**
   * These patterns identify accessibility-tool output.
   * 
   * They are not treated as runtime errors here because accessibility
   * validation belongs to the dedicated accessibility test.
   */
  const ACCESSIBILITY_PATTERNS = [
    'Fix any of the following:',
    'Element has insufficient color contrast',
    'Element should have focusable content',
    'Element should be focusable',
  ];

  /**
   * The browser may emit this generic console message when a known
   * authentication probe receives HTTP 401.
   * 
   * This message is only classified as expected after the corresponding
   * response has independently been identified as an expected probe.
   */
  const pendingAuthConsoleMessages: string[] = [];

  page.on('console', (message) => {
    if (message.type() !== 'error') {
      return;
    }

    const text = message.text();

    if (ACCESSIBILITY_PATTERNS.some((pattern) => text.includes(pattern))) {
      evidence.accessibilityFindings.push(text);
      return;
    }

    if (KNOWN_DEV_DIAGNOSTICS.some((pattern) => text.includes(pattern))) {
      evidence.expectedDiagnostics.push(text);
      return;
    }

    if (
      text.includes(
        'Failed to load resource: the server responded with a status of 401',
      )
    ) {
      /**
       * Do not immediately classify this as expected.
       * 
       * The matching response handler below will determine whether a
       * known endpoint actually returned 401.
       */
      pendingAuthConsoleMessages.push(text);
      return;
    }

    evidence.unexpectedConsoleErrors.push(text);
  });

  page.on('pageerror', (error) => {
    evidence.pageErrors.push(error.message);
  });

  page.on('requestfailed', (request) => {
    const failureInfo = {
      method: request.method(),
      url: request.url(),
      errorText: request.failure()?.errorText ?? 'unknown failure',
    };

    evidence.failedRequests.push(
      `${failureInfo.method} ${failureInfo.url} — ${failureInfo.errorText}`,
    );
  });

  page.on('response', (response) => {
    const request = response.request();
    const method = request.method();
    const url = response.url();
    const status = response.status();

    const expectedProbe = isExpectedAuthProbe(method, url, status);

    if (!expectedProbe) {
      return;
    }

    const probeDescription = `${method} ${url} - ${status} (${expectedProbe.description})`;

    evidence.expectedAuthProbes.push(probeDescription);

    /**
     * Only now may the matching generic browser console message be
     * reclassified as an expected diagnostic.
     */
    if (status === 401 && pendingAuthConsoleMessages.length > 0) {
      const matchingMessageIndex = pendingAuthConsoleMessages.findIndex(
        (message) =>
          message.includes(
            'Failed to load resource: the server responded with a status of 401',
          ),
      );

      if (matchingMessageIndex !== -1) {
        const [matchingMessage] = pendingAuthConsoleMessages.splice(
          matchingMessageIndex,
          1,
        );

        evidence.expectedDiagnostics.push(matchingMessage);
      }
    }
  });

  return evidence;
}

function assertNoRuntimeErrors(
  evidence: BrowserEvidence,
  brandName: string,
  context: string,
): void {
  expect(
    evidence.pageErrors,
    `[${brandName}] JavaScript exceptions detected at ${context}:\n` +
      evidence.pageErrors.join('\n'),
  ).toEqual([]);

  expect(
    evidence.unexpectedConsoleErrors,
    `[${brandName}] Unexpected console errors detected at ${context}:\n` +
      evidence.unexpectedConsoleErrors.join('\n'),
  ).toEqual([]);

  expect(
    evidence.failedRequests,
    `[${brandName}] Failed network requests detected at ${context}:\n` +
      evidence.failedRequests.join('\n'),
  ).toEqual([]);
}

function logClassifiedEvidence(
  evidence: BrowserEvidence,
  brandName: string,
  context: string,
): void {
  if (evidence.expectedDiagnostics.length > 0) {
    console.log(
      `[${brandName}] Expected diagnostics at ${context}:`,
      evidence.expectedDiagnostics,
    );
  }

  if (evidence.expectedAuthProbes.length > 0) {
    console.log(
      `[${brandName}] Expected auth probes at ${context}:`,
      evidence.expectedAuthProbes,
    );
  }

  if (evidence.accessibilityFindings.length > 0) {
    console.log(
      `[${brandName}] Accessibility findings at ${context}: ` +
        `${evidence.accessibilityFindings.length} ` +
        '(validated separately by BROWSER-7)',
    );
  }
}

interface OverflowElement {
  tagName: string;
  id: string;
  className: string;
  left: number;
  right: number;
  width: number;
  scrollWidth: number;
  clientWidth: number;
  text: string;
}

async function findHorizontalOverflow(page: Page): Promise<OverflowElement[]> {
  return page.evaluate(() => {
    const viewportWidth = document.documentElement.clientWidth;

    return Array.from(document.querySelectorAll<HTMLElement>('*'))
      .map((element) => {
        const rect = element.getBoundingClientRect();
        return { element, rect };
      })
      .filter(({ element, rect }) => {
        const style = window.getComputedStyle(element);

        const isHidden =
          style.display === 'none' || style.visibility === 'hidden';

        if (isHidden) {
          return false;
        }

        /**
         * Ignore elements that are intentionally horizontally scrollable.
         * Their internal scroll width is not necessarily page-level overflow.
         */
        const isScrollableContainer =
          style.overflowX === 'auto' || style.overflowX === 'scroll';

        if (isScrollableContainer) {
          return false;
        }

        return rect.left < -1 || rect.right > viewportWidth + 1;
      })
      .map(({ element, rect }) => ({
        tagName: element.tagName,
        id: element.id,
        className:
          typeof element.className === 'string' ? element.className : '',
        left: Math.round(rect.left * 100) / 100,
        right: Math.round(rect.right * 100) / 100,
        width: Math.round(rect.width * 100) / 100,
        scrollWidth: element.scrollWidth,
        clientWidth: element.clientWidth,
        text: (element.innerText ?? '').slice(0, 200),
      }))
      .slice(0, 50);
  });
}

async function assertNoUnexpectedHorizontalOverflow(
  page: Page,
  brandName: string,
  viewportName: string,
): Promise<void> {
  const documentOverflow = await page.evaluate(() => {
    return {
      scrollWidth: document.documentElement.scrollWidth,
      clientWidth: document.documentElement.clientWidth,
      bodyScrollWidth: document.body.scrollWidth,
      bodyClientWidth: document.body.clientWidth,
    };
  });

  const overflowElements = await findHorizontalOverflow(page);

  const hasDocumentOverflow =
    documentOverflow.scrollWidth > documentOverflow.clientWidth + 1;

  if (hasDocumentOverflow) {
    console.log(
      `[${brandName}] Horizontal overflow diagnostics at ${viewportName}:`,
      {
        documentOverflow,
        overflowElements,
      },
    );
  }

  expect(
    hasDocumentOverflow,
    `[${brandName}] Unexpected horizontal overflow at ${viewportName}.\n` +
      `Document metrics: ${JSON.stringify(documentOverflow, null, 2)}\n` +
      `Overflowing elements: ${JSON.stringify(overflowElements, null, 2)}`,
  ).toBe(false);
}

async function login(page: Page, brand: BrandConfig): Promise<void> {
  await page.goto(`${brand.baseUrl}/login`, { waitUntil: 'networkidle' });
  await page.waitForSelector('input#email', {
    state: 'visible',
    timeout: 15000,
  });
  await page.fill('input#email', brand.email!);
  await page.fill('input#password', brand.password!);
  await page.waitForTimeout(1000); // React hydration

  // Wait for login response
  const loginResponsePromise = page.waitForResponse(
    (response) =>
      response.request().method() === 'POST' &&
      response.url().includes('/api/auth/login'),
    { timeout: 35000 },
  );

  await page.click('button[type="submit"]');
  await loginResponsePromise;

  // Wait for navigation away from login
  await page.waitForURL((url) => !url.href.includes('/login'), {
    timeout: 10000,
  });
}

async function navigateToTutorial(page: Page, brand: BrandConfig): Promise<void> {
  const tutorialUrl = `${brand.baseUrl}${brand.tutorialPath}`;
  await page.goto(tutorialUrl, { waitUntil: 'domcontentloaded' });
  // Wait for TutorialPageShell client-side initialization
  await page.waitForTimeout(3000);
}

